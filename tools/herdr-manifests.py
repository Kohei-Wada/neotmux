#!/usr/bin/env python3
"""Turns herdr's agent manifests into neotmux rulesets, unchanged.

    tools/herdr-manifests.py <herdr checkout>

Reads <herdr>/src/detect/manifests/*.toml and writes runtime/lua/neotmux/agents/<id>.lua for
each, except Claude Code's: runtime/lua/neotmux/agents/claude.lua is a port by hand, corrected
against captured screens, and is not replaced. Run it again on a newer herdr to take its
manifests as they are there, and update the commit NOTICE names.
"""

import pathlib
import subprocess
import sys
import tomllib

# herdr's `lookup_agent` in src/detect/mod.rs: the process names each agent is identified by.
LOOKUP = {
    "pi": ["pi"],
    "claude": ["claude", "claude-code"],
    "codex": ["codex"],
    "gemini": ["gemini"],
    "cursor": ["cursor", "cursor-agent"],
    "devin": ["devin", "devin-cli", "devin cli"],
    "agy": ["agy", "antigravity", "antigravity-cli"],
    "cline": ["cline", ".cline"],
    "opencode": ["opencode", "opencode2", "open-code"],
    "copilot": ["copilot", "github-copilot", "ghcs"],
    "kimi": ["kimi", "kimi-code", "kimi code"],
    "kiro": ["kiro", "kiro-cli"],
    "droid": ["droid"],
    "amp": ["amp", "amp-local"],
    "grok": ["grok", "grok-build"],
    "hermes": ["hermes", "hermes-agent"],
    "kilo": ["kilo", "kilo-code", "kilo code"],
    "qodercli": ["qodercli", "qoderclicn", "qoder", "qodercn"],
    "qwen": ["qwen", "qwen-code", "qwen code"],
    "letta": ["letta", "letta-code", "letta code"],
    "maki": ["maki"],
    "muse": ["muse", "muse-code", "muse-cli"],
}

HAND_PORTED = {"claude"}


def string(value):
    level = 0
    # `value + "]"`: a string ending in `]` would otherwise close on its own last character.
    while f"]{'=' * level}]" in value + "]":
        level += 1
    eq = "=" * level
    # A long string drops a newline right after its opening bracket; herdr's never start with one.
    return f"[{eq}[{value}]{eq}]"


def literal(value, indent):
    pad = "  " * indent
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return string(value)
    if isinstance(value, list):
        if not value:
            return "{}"
        items = [f"{pad}  {literal(item, indent + 1)}," for item in value]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(value, dict):
        items = []
        for key, item in value.items():
            name = key if key.isidentifier() and key != "not" else f'["{key}"]'
            items.append(f"{pad}  {name} = {literal(item, indent + 1)},")
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    raise TypeError(f"no Lua literal for {value!r}")


def main():
    herdr = pathlib.Path(sys.argv[1])
    commit = subprocess.run(
        ["git", "-C", herdr, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    out = pathlib.Path(__file__).resolve().parent.parent / "runtime/lua/neotmux/agents"
    ids = []
    for path in sorted((herdr / "src/detect/manifests").glob("*.toml")):
        manifest = tomllib.loads(path.read_text())
        id = manifest["id"]
        if id in HAND_PORTED:
            continue
        names = list(LOOKUP[id])
        for alias in manifest.get("aliases", []):
            if not alias.startswith("herdr:") and alias not in names:
                names.append(alias)
        data = {"id": id, "names": names, "rules": manifest["rules"]}
        body = (
            f"-- herdr's src/detect/manifests/{path.name}, version {manifest['version']}, at\n"
            f"-- herdrdev/herdr {commit}. Apache-2.0; see NOTICE.\n"
            f"-- Generated by tools/herdr-manifests.py: do not edit, run it again.\n"
            f"return require(\"neotmux.manifest\").ruleset({literal(data, 0)})\n"
        )
        (out / f"{id}.lua").write_text(body)
        ids.append(id)
    print(" ".join(ids))


if __name__ == "__main__":
    main()
